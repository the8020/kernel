const generatedHeader = "// Code generated by kernel/cbus/gen. DO NOT EDIT.\n"

type handlerDefinition struct {
	File   string `toml:"file"`
	Symbol string `toml:"symbol"`
}
type exampleDefinition struct {
	Command string `toml:"command"`
}
type commandDefinition struct {
	Version         int                 `toml:"version"`
	ID              string              `toml:"id"`
	Path            []string            `toml:"path"`
	Aliases         [][]string          `toml:"aliases"`
	Summary         string              `toml:"summary"`
	Description     string              `toml:"description"`
	MutatesState    bool                `toml:"mutates_state"`
	RestartBehavior string              `toml:"restart_behavior"`
	Handler         handlerDefinition   `toml:"handler"`
	Parameters      []core.Parameter    `toml:"parameters"`
	Result          []core.ResultField  `toml:"result"`
	Examples        []exampleDefinition `toml:"examples"`
	definitionFile  string
	packageImport   string
}

type runtimeProtocolSchema struct {
	ProtocolVersion        int      `json:"protocol_version"`
	Messages               []string `json:"messages"`
	RequiredEnvelopeFields []string `json:"required_envelope_fields"`
}

type runtimeVersions struct {
	RuntimeProtocolVersion int `toml:"runtime_protocol_version"`
}

type moduleRequirement struct {
	Path    string
	Version string
}

type rootModule struct {
	Path         string
	GoVersion    string
	Requirements []moduleRequirement
}

func main() {
	root, err := os.Getwd()
	if err == nil {
		err = generate(root)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "generation:", err)
		os.Exit(1)
	}
}

func generate(root string) error {
	module, err := readRootModule(root)
	if err != nil {
		return err
	}
	modulePath := module.Path
	commands, err := discoverCommands(root, modulePath)
	if err != nil {
		return err
	}
	definitions, err := discoverSettings(root)
	if err != nil {
		return err
	}
	protocol, err := readRuntimeProtocol(root)
	if err != nil {
		return err
	}
	base := filepath.Join(root, ".development", "generated")
	protocolGo := generateRuntimeProtocolGo(protocol)
	files := map[string][]byte{
		filepath.Join(base, "go.mod"):                                                    generatedModule(module),
		filepath.Join(base, "cbus", "catalog", "catalog.go"):                             generateCommandCatalog(commands),
		filepath.Join(base, "cbus", "registry", "registry.go"):                           generateRegistry(commands, modulePath),
		filepath.Join(base, "settings", "catalog.go"):                                    generateSettingCatalog(definitions),
		filepath.Join(base, "cmd", "kernel", "main.go"):                                  generateKernelMain(),
		filepath.Join(base, "cmd", "admin", "main.go"):                                   generateAdminMain(),
		filepath.Join(base, "runtime", "protocol.go"):                                    protocolGo,
		filepath.Join(root, "defaults", "config", "runtime", "protocol", "generated.ts"): generateRuntimeProtocolTypeScript(protocol),
		filepath.Join(root, "kernel", "runtime", "protocol", "generated.go"):             protocolGo,
	}
	for path, data := range files {
		if strings.HasSuffix(path, ".go") {
			data, err = format.Source(data)
			if err != nil {
				return fmt.Errorf("format %s: %w\n%s", path, err, data)
			}
		}
		if err := writeChanged(path, data); err != nil {
			return err
		}
	}
	return nil
}

func readRuntimeProtocol(root string) (runtimeProtocolSchema, error) {
	path := filepath.Join(root, "defaults", "config", "runtime", "protocol", "schema.json")
	data, err := os.ReadFile(path)
	if err != nil {
		return runtimeProtocolSchema{}, fmt.Errorf("read runtime protocol schema: %w", err)
	}
	var schema runtimeProtocolSchema
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&schema); err != nil {
		return schema, fmt.Errorf("parse runtime protocol schema: %w", err)
	}
	if schema.ProtocolVersion < 1 {
		return schema, errors.New("runtime protocol version must be positive")
	}
	if len(schema.Messages) == 0 {
		return schema, errors.New("runtime protocol has no messages")
	}
	seen := map[string]bool{}
	for _, message := range schema.Messages {
		if !validName(message) || seen[message] {
			return schema, fmt.Errorf("invalid or duplicate runtime protocol message %q", message)
		}
		seen[message] = true
	}
	required := map[string]bool{}
	for _, field := range schema.RequiredEnvelopeFields {
		required[field] = true
	}
	for _, field := range []string{"protocol_version", "message_type", "runtime_group_id"} {
		if !required[field] {
			return schema, fmt.Errorf("runtime protocol envelope must require %s", field)
		}
	}
	versionsData, err := os.ReadFile(filepath.Join(root, "defaults", "config", "runtime", "versions.toml"))
	if err != nil {
		return schema, fmt.Errorf("read runtime versions: %w", err)
	}
	var versions runtimeVersions
	if err := toml.Unmarshal(versionsData, &versions); err != nil {
		return schema, fmt.Errorf("parse runtime versions: %w", err)
	}
	if versions.RuntimeProtocolVersion != schema.ProtocolVersion {
		return schema, fmt.Errorf("runtime protocol version %d does not match versions manifest %d", schema.ProtocolVersion, versions.RuntimeProtocolVersion)
	}
	return schema, nil
}

func generateRuntimeProtocolGo(schema runtimeProtocolSchema) []byte {
	var output strings.Builder
	output.WriteString(generatedHeader)
	output.WriteString("package protocol\n\nimport (\n\t\"encoding/json\"\n\t\"fmt\"\n)\n\n")
	fmt.Fprintf(&output, "const ProtocolVersion = %d\n\n", schema.ProtocolVersion)
	output.WriteString("type MessageType string\n\nconst (\n")
	for _, message := range schema.Messages {
		fmt.Fprintf(&output, "\tMessage%s MessageType = %q\n", exportedName(message), message)
	}
	output.WriteString(")\n\n")
	output.WriteString("var validMessageTypes = map[MessageType]bool{\n")
	for _, message := range schema.Messages {
		fmt.Fprintf(&output, "\tMessage%s: true,\n", exportedName(message))
	}
	output.WriteString("}\n\n")
	output.WriteString("type Envelope struct {\n\tProtocolVersion int `json:\"protocol_version\"`\n\tMessageType MessageType `json:\"message_type\"`\n\tRuntimeGroupID string `json:\"runtime_group_id\"`\n\tCorrelationID string `json:\"correlation_id,omitempty\"`\n\tPayload json.RawMessage `json:\"payload,omitempty\"`\n}\n\n")
	output.WriteString("func (e Envelope) Validate() error {\n\tif e.ProtocolVersion != ProtocolVersion { return fmt.Errorf(\"unsupported runtime protocol version %d\", e.ProtocolVersion) }\n\tif !validMessageTypes[e.MessageType] { return fmt.Errorf(\"unknown runtime message type %q\", e.MessageType) }\n\tif e.RuntimeGroupID == \"\" { return fmt.Errorf(\"runtime_group_id is required\") }\n\treturn nil\n}\n")
	return []byte(output.String())
}

func generateRuntimeProtocolTypeScript(schema runtimeProtocolSchema) []byte {
	var output strings.Builder
	output.WriteString("// Code generated by kernel/cbus/gen. DO NOT EDIT.\n")
	fmt.Fprintf(&output, "export const PROTOCOL_VERSION = %d as const;\n\n", schema.ProtocolVersion)
	output.WriteString("export const MESSAGE_TYPES = [\n")
	for _, message := range schema.Messages {
		fmt.Fprintf(&output, "  %q,\n", message)
	}
	output.WriteString("] as const;\n\nexport type MessageType = (typeof MESSAGE_TYPES)[number];\n\n")
	output.WriteString("export interface Envelope<T = Record<string, unknown>> {\n  protocol_version: typeof PROTOCOL_VERSION;\n  message_type: MessageType;\n  runtime_group_id: string;\n  correlation_id?: string;\n  payload?: T;\n}\n\n")
	output.WriteString(`export function assertEnvelope(value: unknown): asserts value is Envelope {
  if (typeof value !== "object" || value === null) {
    throw new TypeError("runtime message must be an object");
  }
  const message = value as Record<string, unknown>;
  if (message.protocol_version !== PROTOCOL_VERSION) {
    throw new TypeError(
      ` + "`unsupported runtime protocol version ${message.protocol_version}`" + `,
    );
  }
  if (!MESSAGE_TYPES.includes(message.message_type as MessageType)) {
    throw new TypeError(` + "`unknown runtime message type ${message.message_type}`" + `);
  }
  if (
    typeof message.runtime_group_id !== "string" ||
    message.runtime_group_id.length === 0
  ) throw new TypeError("runtime_group_id is required");
}
`)
	return []byte(output.String())
}

func exportedName(value string) string {
	var output strings.Builder
	upper := true
	for _, character := range value {
		if character == '_' {
			upper = true
			continue
		}
		if upper {
			output.WriteRune(unicode.ToUpper(character))
			upper = false
		} else {
			output.WriteRune(character)
		}
	}
	return output.String()
}

func readRootModule(root string) (rootModule, error) {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return rootModule{}, fmt.Errorf("read go.mod: %w", err)
	}
	var module rootModule
	inRequireBlock := false
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(line)
		if inRequireBlock {
			if len(fields) == 0 || strings.HasPrefix(fields[0], "//") {
				continue
			}
			if len(fields) == 1 && fields[0] == ")" {
				inRequireBlock = false
				continue
			}
			if len(fields) >= 2 {
				module.Requirements = append(module.Requirements, moduleRequirement{Path: fields[0], Version: fields[1]})
			}
			continue
		}
		if len(fields) == 2 && fields[0] == "module" {
			module.Path = fields[1]
			continue
		}
		if len(fields) == 2 && fields[0] == "go" {
			module.GoVersion = fields[1]
			continue
		}
		if len(fields) == 2 && fields[0] == "require" && fields[1] == "(" {
			inRequireBlock = true
			continue
		}
		if len(fields) >= 3 && fields[0] == "require" {
			module.Requirements = append(module.Requirements, moduleRequirement{Path: fields[1], Version: fields[2]})
		}
	}
	if module.Path == "" {
		return rootModule{}, errors.New("go.mod has no module directive")
	}
	if module.GoVersion == "" {
		return rootModule{}, errors.New("go.mod has no go directive")
	}
	sort.Slice(module.Requirements, func(left, right int) bool {
		return module.Requirements[left].Path < module.Requirements[right].Path
	})
	return module, nil
}

func discoverCommands(root, modulePath string) ([]commandDefinition, error) {
	commandRoot := filepath.Join(root, "kernel", "cbus", "commands")
	var definitions []commandDefinition
	err := filepath.WalkDir(commandRoot, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || entry.Name() != "command.toml" {
			return nil
		}
		definition, err := parseCommand(root, modulePath, path)
		if err != nil {
			return err
		}
		definitions = append(definitions, definition)
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(definitions) == 0 {
		return nil, errors.New("no command definitions found")
	}
	ids := map[string]string{}
	routes := map[string]string{}
	for _, definition := range definitions {
		if previous, ok := ids[definition.ID]; ok {
			return nil, fmt.Errorf("duplicate command ID %q in %s and %s", definition.ID, previous, definition.definitionFile)
		}
		ids[definition.ID] = definition.definitionFile
		paths := append([][]string{definition.Path}, definition.Aliases...)
		for _, path := range paths {
			route := strings.Join(path, "\x00")
			if previous, ok := routes[route]; ok {
				return nil, fmt.Errorf("conflicting command path %q in %s and %s", core.PathString(path), previous, definition.definitionFile)
			}
			routes[route] = definition.definitionFile
		}
	}
	sort.Slice(definitions, func(i, j int) bool { return definitions[i].ID < definitions[j].ID })
	return definitions, nil
}

func parseCommand(root, modulePath, path string) (commandDefinition, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return commandDefinition{}, err
	}
	var definition commandDefinition
	decoder := toml.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&definition); err != nil {
		return definition, fmt.Errorf("parse %s: %w", path, err)
	}
	definition.definitionFile = path
	if definition.Version != 1 {
		return definition, fmt.Errorf("%s: unsupported schema version %d", path, definition.Version)
	}
	if !validID(definition.ID) {
		return definition, fmt.Errorf("%s: invalid command ID %q", path, definition.ID)
	}
	if err := validatePath(definition.Path); err != nil {
		return definition, fmt.Errorf("%s: primary path: %w", path, err)
	}
	for _, alias := range definition.Aliases {
		if err := validatePath(alias); err != nil {
			return definition, fmt.Errorf("%s: alias: %w", path, err)
		}
	}
	if strings.TrimSpace(definition.Summary) == "" || strings.TrimSpace(definition.Description) == "" {
		return definition, fmt.Errorf("%s: summary and description are required", path)
	}
	if strings.TrimSpace(definition.RestartBehavior) == "" {
		return definition, fmt.Errorf("%s: restart_behavior is required", path)
	}
	positions := map[int]bool{}
	options := map[string]bool{}
	names := map[string]bool{}
	positionalCount := 0
	for _, parameter := range definition.Parameters {
		if !validName(parameter.Name) {
			return definition, fmt.Errorf("%s: invalid parameter name %q", path, parameter.Name)
		}
		if names[parameter.Name] {
			return definition, fmt.Errorf("%s: duplicate parameter %q", path, parameter.Name)
		}
		names[parameter.Name] = true
		if parameter.Prompt != "" && strings.TrimSpace(parameter.Prompt) == "" {
			return definition, fmt.Errorf("%s: parameter %s prompt must contain visible text", path, parameter.Name)
		}
		if parameter.Secret {
			if parameter.Prompt != "" {
				return definition, fmt.Errorf("%s: secret parameter %s cannot declare an ordinary prompt", path, parameter.Name)
			}
			if parameter.Type != "string" || parameter.Option != "" || !parameter.Required {
				return definition, fmt.Errorf("%s: secret parameter %s must be a required string without an ordinary option", path, parameter.Name)
			}
			if strings.TrimSpace(parameter.SecretPrompt) == "" || strings.TrimSpace(parameter.SecretConfirmationPrompt) == "" {
				return definition, fmt.Errorf("%s: secret parameter %s requires prompt and confirmation metadata", path, parameter.Name)
			}
			if !validOption(parameter.SecretStdinOption) {
				return definition, fmt.Errorf("%s: secret parameter %s has invalid stdin option", path, parameter.Name)
			}
			if options[parameter.SecretStdinOption] {
				return definition, fmt.Errorf("%s: duplicate parameter option %q", path, parameter.SecretStdinOption)
			}
			options[parameter.SecretStdinOption] = true
		} else if parameter.Option == "" {
			if parameter.Prompt != "" && !parameter.Required {
				return definition, fmt.Errorf("%s: prompted parameter %s must be required", path, parameter.Name)
			}
			if positions[parameter.Position] {
				return definition, fmt.Errorf("%s: duplicate parameter position %d", path, parameter.Position)
			}
			positions[parameter.Position] = true
			positionalCount++
			if parameter.Position < 0 {
				return definition, fmt.Errorf("%s: negative parameter position", path)
			}
		} else {
			if parameter.Prompt != "" {
				return definition, fmt.Errorf("%s: prompted parameter %s must be positional", path, parameter.Name)
			}
			if !validOption(parameter.Option) {
				return definition, fmt.Errorf("%s: invalid parameter option %q", path, parameter.Option)
			}
			if options[parameter.Option] {
				return definition, fmt.Errorf("%s: duplicate parameter option %q", path, parameter.Option)
			}
			options[parameter.Option] = true
		}
		if parameter.Type != "string" && parameter.Type != "integer" && parameter.Type != "boolean" {
			return definition, fmt.Errorf("%s: invalid parameter type %q", path, parameter.Type)
		}
		if parameter.Description == "" {
			return definition, fmt.Errorf("%s: parameter %s has no description", path, parameter.Name)
		}
	}
	for index := 0; index < positionalCount; index++ {
		if !positions[index] {
			return definition, fmt.Errorf("%s: parameter positions must be contiguous", path)
		}
	}
	if len(definition.Result) == 0 {
		return definition, fmt.Errorf("%s: result fields are required", path)
	}
	resultTypes := map[string]bool{"string": true, "integer": true, "boolean": true, "any": true, "object": true, "array": true}
	resultNames := map[string]bool{}
	for _, field := range definition.Result {
		if !validName(field.Name) || resultNames[field.Name] {
			return definition, fmt.Errorf("%s: invalid or duplicate result field %q", path, field.Name)
		}
		resultNames[field.Name] = true
		if !resultTypes[field.Type] {
			return definition, fmt.Errorf("%s: invalid result type %q", path, field.Type)
		}
	}
	if len(definition.Examples) == 0 {
		return definition, fmt.Errorf("%s: at least one example is required", path)
	}
	for _, example := range definition.Examples {
		if strings.TrimSpace(example.Command) == "" {
			return definition, fmt.Errorf("%s: empty example", path)
		}
	}
	if definition.Handler.File == "" || !validExportedIdentifier(definition.Handler.Symbol) {
		return definition, fmt.Errorf("%s: invalid handler declaration", path)
	}
	declared := filepath.Clean(filepath.Join(root, filepath.FromSlash(definition.Handler.File)))
	relative, err := filepath.Rel(root, declared)
	if err != nil {
		return definition, err
	}
	if relative == "kernel" || strings.HasPrefix(relative, "kernel"+string(filepath.Separator)) {
	} else {
		return definition, fmt.Errorf("%s: handler must be inside kernel/", path)
	}
	info, err := os.Stat(declared)
	if err != nil {
		return definition, fmt.Errorf("%s: handler file %q: %w", path, definition.Handler.File, err)
	}
	if info.IsDir() {
		return definition, fmt.Errorf("%s: handler file is a directory", path)
	}
	parsed, err := parser.ParseFile(token.NewFileSet(), declared, nil, 0)
	if err != nil {
		return definition, fmt.Errorf("%s: parse handler: %w", path, err)
	}
	found := false
	for _, declaration := range parsed.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if ok && function.Recv == nil && function.Name.Name == definition.Handler.Symbol {
			found = true
			break
		}
	}
	if !found {
		return definition, fmt.Errorf("%s: constructor symbol %s not found in %s", path, definition.Handler.Symbol, definition.Handler.File)
	}
	directoryRelative, err := filepath.Rel(root, filepath.Dir(declared))
	if err != nil {
		return definition, err
	}
	definition.packageImport = modulePath + "/" + filepath.ToSlash(directoryRelative)
	return definition, nil
}

func validID(value string) bool {
	parts := strings.Split(value, ".")
	if len(parts) < 2 {
		return false
	}
	for _, part := range parts {
		if !validName(part) {
			return false
		}
	}
	return true
}
func validName(value string) bool {
	if value == "" {
		return false
	}
	for index, r := range value {
		if !((r >= 'a' && r <= 'z') || r == '_' || (index > 0 && r >= '0' && r <= '9')) {
			return false
		}
	}
	return true
}
func validOption(value string) bool {
	if value == "" {
		return false
	}
	for index, r := range value {
		if !((r >= 'a' && r <= 'z') || (index > 0 && r >= '0' && r <= '9') || (index > 0 && r == '-')) {
			return false
		}
	}
	return true
}
func validatePath(path []string) error {
	if len(path) == 0 {
		return errors.New("path is empty")
	}
	for _, part := range path {
		if !validOption(part) {
			return fmt.Errorf("invalid component %q", part)
		}
	}
	return nil
}
func validExportedIdentifier(value string) bool {
	if value == "" || !unicode.IsUpper([]rune(value)[0]) {
		return false
	}
	for _, r := range value {
		if !(unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_') {
			return false
		}
	}
	return true
}

func discoverSettings(root string) ([]settings.Definition, error) {
	definitionRoot := filepath.Join(root, "kernel", "settings", "definitions")
	var definitions []settings.Definition
	seen := map[string]string{}
	err := filepath.WalkDir(definitionRoot, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".toml" {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var definition settings.Definition
		decoder := toml.NewDecoder(bytes.NewReader(data))
		decoder.DisallowUnknownFields()
		if err := decoder.Decode(&definition); err != nil {
			return fmt.Errorf("parse %s: %w", path, err)
		}
		definition, err = settings.ValidateDefinition(definition)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		if previous, ok := seen[definition.Key]; ok {
			return fmt.Errorf("duplicate setting %q in %s and %s", definition.Key, previous, path)
		}
		seen[definition.Key] = path
		definitions = append(definitions, definition)
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(definitions) == 0 {
		return nil, errors.New("no setting definitions found")
	}
	sort.Slice(definitions, func(i, j int) bool { return definitions[i].Key < definitions[j].Key })
	return definitions, nil
}

func generateCommandCatalog(definitions []commandDefinition) []byte {
	var output strings.Builder
	output.WriteString(generatedHeader)
	output.WriteString("package catalog\n\nimport \"the8020/kernel/cbus/core\"\n\nvar Commands = []core.Command{\n")
	for _, definition := range definitions {
		fmt.Fprintf(&output, "{Version:%d, ID:%q, Path:%s, Aliases:%s, Summary:%q, Description:%q, MutatesState:%t, RestartBehavior:%q, Parameters:%s, Result:%s, Examples:%s},\n", definition.Version, definition.ID, stringSlice(definition.Path), nestedStringSlice(definition.Aliases), definition.Summary, definition.Description, definition.MutatesState, definition.RestartBehavior, parametersLiteral(definition.Parameters), resultLiteral(definition.Result), exampleLiteral(definition.Examples))
	}
	output.WriteString("}\n")
	return []byte(output.String())
}
func stringSlice(values []string) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = strconv.Quote(value)
	}
	return "[]string{" + strings.Join(parts, ",") + "}"
}
func nestedStringSlice(values [][]string) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = stringSlice(value)
	}
	return "[][]string{" + strings.Join(parts, ",") + "}"
}
func parametersLiteral(values []core.Parameter) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = fmt.Sprintf("{Name:%q,Type:%q,Description:%q,Option:%q,Position:%d,Required:%t,Prompt:%q,Secret:%t,SecretPrompt:%q,SecretConfirmationPrompt:%q,SecretStdinOption:%q}", value.Name, value.Type, value.Description, value.Option, value.Position, value.Required, value.Prompt, value.Secret, value.SecretPrompt, value.SecretConfirmationPrompt, value.SecretStdinOption)
	}
	return "[]core.Parameter{" + strings.Join(parts, ",") + "}"
}
func resultLiteral(values []core.ResultField) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = fmt.Sprintf("{Name:%q,Type:%q}", value.Name, value.Type)
	}
	return "[]core.ResultField{" + strings.Join(parts, ",") + "}"
}
func exampleLiteral(values []exampleDefinition) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = strconv.Quote(value.Command)
	}
	return "[]string{" + strings.Join(parts, ",") + "}"
}

func generateRegistry(definitions []commandDefinition, modulePath string) []byte {
	type constructor struct{ path, symbol, alias string }
	constructors := map[string]constructor{}
	seen := map[string]bool{}
	keys := make([]string, 0)
	for _, definition := range definitions {
		key := definition.packageImport + "\x00" + definition.Handler.Symbol
		if !seen[key] {
			seen[key] = true
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	for index, key := range keys {
		path, symbol, _ := strings.Cut(key, "\x00")
		constructors[key] = constructor{path: path, symbol: symbol, alias: fmt.Sprintf("handler%d", index)}
	}
	var output strings.Builder
	output.WriteString(generatedHeader)
	output.WriteString("package registry\n\nimport (\n\t\"the8020/kernel/cbus/core\"\n\t\"the8020/kernel/services\"\n\t\"the8020.generated/cbus/catalog\"\n")
	for _, key := range keys {
		value := constructors[key]
		fmt.Fprintf(&output, "\t%s %q\n", value.alias, value.path)
	}
	output.WriteString(")\n\nfunc Register(registry *core.Registry, serviceSet *services.Services) error {\n")
	for index, definition := range definitions {
		key := definition.packageImport + "\x00" + definition.Handler.Symbol
		value := constructors[key]
		fmt.Fprintf(&output, "if err := registry.Register(catalog.Commands[%d], %s.%s(serviceSet)); err != nil { return err }\n", index, value.alias, value.symbol)
	}
	output.WriteString("return nil\n}\n")
	return []byte(output.String())
}

func generateSettingCatalog(definitions []settings.Definition) []byte {
	var output strings.Builder
	output.WriteString(generatedHeader)
	output.WriteString("package settingscatalog\n\nimport \"the8020/kernel/settings\"\n\nfunc integerPointer(value int64) *int64 { return &value }\n\nvar Definitions = []settings.Definition{\n")
	for _, definition := range definitions {
		minimum, maximum := "nil", "nil"
		if definition.Minimum != nil {
			minimum = fmt.Sprintf("integerPointer(%d)", *definition.Minimum)
		}
		if definition.Maximum != nil {
			maximum = fmt.Sprintf("integerPointer(%d)", *definition.Maximum)
		}
		fmt.Fprintf(&output, "{Key:%q,Type:%q,Storage:%q,Default:%s,Environment:%q,Minimum:%s,Maximum:%s,Allowed:%s,Pattern:%q,RuntimeMutable:%t,RestartRequired:%t,Description:%q},\n", definition.Key, definition.Type, definition.Storage, settingValueLiteral(definition.Default), definition.Environment, minimum, maximum, stringSlice(definition.Allowed), definition.Pattern, definition.RuntimeMutable, definition.RestartRequired, definition.Description)
	}
	output.WriteString("}\n")
	return []byte(output.String())
}
func settingValueLiteral(value any) string {
	switch typed := value.(type) {
	case string:
		return strconv.Quote(typed)
	case bool:
		return strconv.FormatBool(typed)
	case int64:
		return fmt.Sprintf("int64(%d)", typed)
	case settings.ByteSize:
		return fmt.Sprintf("settings.ByteSize(%d)", typed)
	default:
		panic(fmt.Sprintf("unsupported setting literal %T", value))
	}
}

func generatedModule(module rootModule) []byte {
	var output strings.Builder
	fmt.Fprintf(&output, "module the8020.generated\n\ngo %s\n\nrequire %s v0.0.0\n", module.GoVersion, module.Path)
	if len(module.Requirements) > 0 {
		output.WriteString("\nrequire (\n")
		for _, requirement := range module.Requirements {
			if requirement.Path == module.Path {
				continue
			}
			fmt.Fprintf(&output, "\t%s %s // indirect\n", requirement.Path, requirement.Version)
		}
		output.WriteString(")\n")
	}
	fmt.Fprintf(&output, "\nreplace %s => ../..\n", module.Path)
	return []byte(output.String())
}
