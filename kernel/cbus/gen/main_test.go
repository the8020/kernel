func TestEveryDevelopmentCommandExampleTraversesBothCLIParsingModes(t *testing.T) {
	working, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	root := filepath.Clean(filepath.Join(working, "..", "..", ".."))
	definitions, err := discoverCommands(root, "the8020")
	if err != nil {
		t.Fatal(err)
	}
	catalog := make([]core.Command, 0, len(definitions))
	for _, definition := range definitions {
		examples := make([]string, 0, len(definition.Examples))
		for _, example := range definition.Examples {
			examples = append(examples, example.Command)
		}
		catalog = append(catalog, core.Command{Version: definition.Version, ID: definition.ID, Path: definition.Path, Aliases: definition.Aliases, Summary: definition.Summary, Description: definition.Description, Parameters: definition.Parameters, Result: definition.Result, MutatesState: definition.MutatesState, RestartBehavior: definition.RestartBehavior, Examples: examples})
	}
	executor := &catalogExecutor{}
	runner := cli.New(catalog, executor)
	count := 0
	for _, command := range catalog {
		if !strings.HasPrefix(command.ID, "development.") && !strings.HasPrefix(command.ID, "package.repository.") {
			continue
		}
		if len(command.Examples) == 0 {
			t.Fatalf("%s has no external CLI example", command.ID)
		}
		tokens, err := cli.SplitLine(command.Examples[0])
		if err != nil {
			t.Fatalf("split interactive %s example: %v", command.ID, err)
		}
		for _, mode := range []string{"one-shot", "interactive"} {
			var output bytes.Buffer
			invocation := append([]string(nil), tokens...)
			if code := runner.Run(context.Background(), invocation, false, &output); code != 0 {
				t.Fatalf("%s %s example failed with %d: %s", command.ID, mode, code, output.String())
			}
			if executor.commandIDs[len(executor.commandIDs)-1] != command.ID {
				t.Fatalf("%s %s dispatched %s", command.ID, mode, executor.commandIDs[len(executor.commandIDs)-1])
			}
		}
		count++
	}
	if count != 22 {
		t.Fatalf("development CLI command count = %d, want 22", count)
	}
}

